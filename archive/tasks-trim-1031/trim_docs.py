import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))


def sub(path, pairs):
    p = os.path.join(ROOT, 'tasks', 'gameplay', path)
    raw = open(p, 'rb').read().decode('utf-8')
    CR, LF = chr(13), chr(10)
    crlf = (CR + LF) in raw
    b = raw.replace(CR + LF, LF)
    for a, c in pairs:
        assert a in b, (path, a[:40])
        b = b.replace(a, c, 1)
    out = b.replace(LF, CR + LF) if crlf else b
    open(p, 'wb').write(out.encode('utf-8'))
    print(path, len(out.encode('utf-8')))


