def cut_section(path, head_start, new_text):
    p = os.path.join(ROOT, 'tasks', 'gameplay', path)
    raw = open(p, 'rb').read().decode('utf-8')
    CR, LF = chr(13), chr(10)
    crlf = (CR + LF) in raw
    b = raw.replace(CR + LF, LF)
    i = b.index(head_start)
    j = b.find(LF + '## ', i + 5)
    k = b.find(LF + '### ', i + 5)
    ends = [x for x in (j, k) if x != -1]
    end = min(ends) + 1 if ends else len(b)
    b = b[:i] + new_text + b[end:]
    out = b.replace(LF, CR + LF) if crlf else b
    open(p, 'wb').write(out.encode('utf-8'))
    print(path, len(out.encode('utf-8')))


