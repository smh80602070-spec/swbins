// tasks U-0245 — 웹 2나락 장비 표(data-item.js·data-set.js·data-unique.js)를 유니티 C# 표로 뽑는다.
// 정본은 웹 — 표가 바뀌면(자체툴 생성기로 늘어나면) 이것만 다시 돌린다:
//   node saga-unity/tools/gen-dungeon-gear.mjs   → Assets/Games/SagaDungeon/Data/GearTables.cs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../../saga-web/saga-dungeon/js');
const out = path.resolve(here, '../Assets/Games/SagaDungeon/Data/GearTables.cs');

const win = { DG: {} };
win.window = win;
const ctx = vm.createContext(win);
for (const f of ['data-item.js', 'data-set.js', 'data-unique.js']) {
  vm.runInContext(fs.readFileSync(path.join(web, f), 'utf8'), ctx, { filename: f });
}
const D = win.DG.itemData, S = win.DG.setData, U = win.DG.uniqueData;
if (!D || !S || !U) throw new Error('웹 표를 못 읽음: ' + Object.keys(win.DG).join(','));

const s = v => v == null ? 'null' : JSON.stringify(String(v));
const f = v => v == null ? '0f' : (Number.isInteger(v) ? v + 'f' : v + 'f');
const eff = e => `new GearEff(${s(e.kind)}, ${s(e.stat)}, ${s(e.eff)}, ${s(e.el)}, ${f(e.v)}, ${e.scale === false ? 'false' : 'true'})`;
const effs = a => `new[] { ${(a || []).map(eff).join(', ')} }`;

const L = [];
L.push('// <auto-generated> tools/gen-dungeon-gear.mjs — 웹 saga-dungeon data-item.js·data-set.js·data-unique.js 그대로. 손으로 고치지 말 것(tasks U-0245).');
L.push('namespace Saga.Dungeon.Data');
L.push('{');
L.push('    public static partial class GearTables');
L.push('    {');
L.push(`        public const int SetTier = ${S.SET_TIER};`);
L.push(`        public const float SetChance = ${S.SET_CHANCE}f;`);
L.push(`        public const float UniqueChance = ${U.UNIQUE_CHANCE}f;`);
L.push(`        public const int UniqueBaseIlvl = ${U.BASE_ILVL};`);
L.push('        public static readonly GearTier[] Tiers =');
L.push('        {');
for (const t of D.TIERS) L.push(`            new GearTier(${t.key}, ${s(t.name)}, ${s(t.hanja)}, ${s(t.color)}, ${f(t.mul)}, ${t.affix}, ${f(t.weight)}),`);
L.push('        };');
L.push('        public static readonly GearBase[] Bases =');
L.push('        {');
for (const b of D.BASES) L.push(`            new GearBase(${s(b.key)}, ${s(b.slot)}, ${s(b.name)}, ${s(b.main)}, ${f(b.base)}, ${s(b.look)}),`);
L.push('        };');
L.push('        public static readonly GearAffix[] Affixes =');
L.push('        {');
for (const a of D.AFFIXES) L.push(`            new GearAffix(${s(a.key)}, ${s(a.kind)}, ${s(a.stat)}, ${s(a.eff)}, ${f(a.lo)}, ${f(a.hi)}, ${s(a.pre)}, ${s(a.post)}, ${s(a.label)}),`);
L.push('        };');
L.push('        public static readonly GearSet[] Sets =');
L.push('        {');
for (const t of S.SETS) {
  const k = t.skill || {};
  const sk = t.skill ? `new GearSetSkill(${s(k.name)}, ${s(k.emoji)}, ${s(k.shape)}, ${f(k.v)}, ${f(k.r)}, ${f(k.far)}, ${f(k.sec)}, ${f(k.cd)}, ${k.shots || 0}, ${f(k.spread)}, ${f(k.kb)}, ${s(k.eff)}, ${s(k.el)}, ${s(k.desc)})` : 'null';
  L.push(`            new GearSet(${s(t.key)}, ${s(t.name)}, new[] { ${t.pieces.map(s).join(', ')} }, ${s(t.desc)}, ${effs(t.bonus[2])}, ${effs(t.bonus[3])}, ${sk}),`);
}
L.push('        };');
L.push('        public static readonly GearUnique[] Uniques =');
L.push('        {');
for (const u of U.UNIQUES) L.push(`            new GearUnique(${s(u.key)}, ${s(u.base)}, ${s(u.name)}, ${s(u.desc)}, ${effs(u.eff)}),`);
L.push('        };');
L.push('    }');
L.push('}');

for (const t of S.SETS) {
  const ks = Object.keys(t.bonus).join(',');
  if (ks !== '2,3') throw new Error(`세트 ${t.key} 보너스 단계 ${ks} — GearSet 은 2·3 점만 안다`);
}
fs.writeFileSync(out, L.join('\r\n') + '\r\n');
console.log(`GearTables.cs — 등급 ${D.TIERS.length}·바탕 ${D.BASES.length}·접사 ${D.AFFIXES.length}·세트 ${S.SETS.length}·고유 ${U.UNIQUES.length}`);
