// tasks U-0246 — 웹 4종횡 장비 표(data-gear.js·data-unique.js·gear-set.js)를 유니티 C# 표로 뽑는다.
// 정본은 웹 — 표가 바뀌면(자체툴 생성기로 늘어나면) 이것만 다시 돌린다:
//   node saga-unity/tools/gen-story-gear.mjs   → Assets/Games/SagaStory/Data/StoryGearTables.cs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '../../saga-web/saga-story/js');
const out = path.resolve(here, '../Assets/Games/SagaStory/Data/StoryGearTables.cs');

const win = { DG: {} };
win.window = win;
const ctx = vm.createContext(win);
for (const f of ['data-gear.js', 'data-unique.js', 'gear-set.js']) {
  vm.runInContext(fs.readFileSync(path.join(web, f), 'utf8'), ctx, { filename: f });
}
const G = win.DG.gearData, U = win.DG.uniqueData, S = win.DG.gearSet;
if (!G || !U || !S) throw new Error('웹 표를 못 읽음: ' + Object.keys(win.DG).join(','));
const gear = G.GEAR || G.gear;
if (!gear) throw new Error('data-gear.js GEAR 없음: ' + Object.keys(G).join(','));

const s = v => v == null ? 'null' : JSON.stringify(String(v));
const n = v => (v == null ? 0 : v);
const L = [];
L.push('// <auto-generated> tools/gen-story-gear.mjs — 웹 saga-story data-gear.js·data-unique.js·gear-set.js 그대로. 손으로 고치지 말 것(tasks U-0246).');
L.push('namespace Saga.Story.Data');
L.push('{');
L.push('    public static partial class StoryGearTables');
L.push('    {');
L.push('        public static readonly StoryGearSlot[] Slots =');
L.push('        {');
for (const sl of G.SLOTS) L.push(`            new StoryGearSlot(${s(sl.key)}, ${s(sl.name)}, ${s(sl.emoji)}),`);
L.push('        };');
L.push('        /// <summary>장비 — 고유는 <see cref="StoryGearDef.Base"/> 가 있다(보스가 그 바탕 Lv.20 을 떨굴 때만).</summary>');
L.push('        public static readonly StoryGearDef[] Gear =');
L.push('        {');
for (const g of gear) L.push(`            new StoryGearDef(${s(g.key)}, ${s(g.slot)}, ${s(g.name)}, ${n(g.need)}, ${n(g.atk)}, ${n(g.def)}, ${n(g.hp)}, ${n(g.price)}, null),`);
for (const u of U.UNIQUES) L.push(`            new StoryGearDef(${s(u.key)}, ${s(u.slot)}, ${s(u.name)}, ${n(u.need)}, ${n(u.atk)}, ${n(u.def)}, ${n(u.hp)}, ${n(u.price)}, ${s(u.base)}),`);
L.push('        };');
L.push('        public static readonly StoryGearSet[] Sets =');
L.push('        {');
for (const t of S.SETS) {
  const b = k => { const x = t.bonus[k] || {}; return `new StoryGearBonus(${k}, ${n(x.atk)}, ${n(x.def)}, ${n(x.hp)})`; };
  const k = t.skill || {};
  const mul = Array.isArray(k.mul) ? k.mul[0] : n(k.mul);
  L.push(`            new StoryGearSet(${s(t.key)}, ${s(t.name)}, new[] { ${t.pieces.map(s).join(', ')} }, new[] { ${Object.keys(t.bonus).map(b).join(', ')} },`);
  L.push(`                ${t.skill ? `new StoryGearSetSkill(${s(k.name)}, ${s(k.emoji)}, ${s(k.effect)}, ${mul}f, ${n(k.r)}f, ${n(k.cd)}f, ${s(k.desc)})` : 'null'}),`);
}
L.push('        };');
L.push('    }');
L.push('}');
fs.writeFileSync(out, L.join('\r\n') + '\r\n');
console.log(`StoryGearTables.cs — 부위 ${G.SLOTS.length}·장비 ${gear.length}·고유 ${U.UNIQUES.length}·세트 ${S.SETS.length}`);
